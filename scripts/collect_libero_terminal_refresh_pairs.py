def _valid_pair_arrays(
    *,
    args: argparse.Namespace,
    episode_id: int,
    initial_state_id: int,
    decision_step: int,
    step_limit: int,
    root_seed: int,
    branch: paired_collector.BranchSpec,
    anchor_input: dict[str, Any],
    endpoint_input: dict[str, Any],
    anchor_result: dict[str, Any],
    endpoint_fresh_result: dict[str, Any],
    actual_prefix: np.ndarray,
    actual_prefix_valid: np.ndarray,
    stale: dict[str, Any],
    fresh: dict[str, Any],
) -> dict[str, np.ndarray]:
    fresh_tensors = paired_collector._teacher_tensors(endpoint_fresh_result)
    arrays = paired_collector._base_arrays(
        args=args,
        episode_id=episode_id,
        initial_state_id=initial_state_id,
        root_index=args.root_index,
        decision_step=decision_step,
        root_seed=root_seed,
        continuation_seed=_logical_seed(
            episode_id=episode_id,
            anchor_decision_step=decision_step,
            slot=0,
            args=args,
        ),
        branch=branch,
        anchor_input=anchor_input,
        endpoint_input=endpoint_input,
        anchor_result=anchor_result,
        current_tensors=fresh_tensors,
        actual_prefix=actual_prefix,
        actual_prefix_valid=actual_prefix_valid,
        endpoint_done=False,
        valid=True,
        invalid_reason="",
    )
    arrays.update(
        {
            "terminal_slot0_absolute_decision_step": np.asarray(
                _logical_slot_step(decision_step, 0), dtype=np.int32
            ),
            "terminal_slot_stride_steps": np.asarray(ACTION_HORIZON, dtype=np.int16),
            "terminal_absolute_environment_step_limit": np.asarray(
                step_limit, dtype=np.int32
            ),
            "terminal_control_step_limit": np.asarray(
                libero_eval._max_steps(args.task_suite_name), dtype=np.int32
            ),
            "common_sunk_anchor_request_calls": np.asarray(1, dtype=np.int16),
            "common_sunk_anchor_request_wall_ms": np.asarray(
                anchor_result["collector_wall_ms"], dtype=np.float32
            ),
            "fresh_decision_refresh_request_calls": np.asarray(1, dtype=np.int16),
            "fresh_decision_refresh_request_wall_ms": np.asarray(
                endpoint_fresh_result["collector_wall_ms"], dtype=np.float32
            ),
        }
    )
    arrays.update(_arm_arrays("stale", stale))
    arrays.update(_arm_arrays("fresh", fresh))
    arrays.update(refresh_collector._progress_arrays("before", stale["before"]))
    arrays.update(refresh_collector._progress_arrays("stale_h6", stale["after_h6"]))
    arrays.update(refresh_collector._progress_arrays("fresh_h6", fresh["after_h6"]))
    arrays.update(
        refresh_collector._progress_arrays("stale_terminal", stale["terminal"])
    )
    arrays.update(
        refresh_collector._progress_arrays("fresh_terminal", fresh["terminal"])
    )
    arrays.update(
        refresh_collector._advantage_arrays(
            "h6",
            stale["after_h6"],
            fresh["after_h6"],
        )
    )
    arrays.update(
        refresh_collector._advantage_arrays(
            "terminal",
            stale["terminal"],
            fresh["terminal"],
        )
    )
    arrays.update(
        {
            "terminal_success_difference": np.asarray(
                int(fresh["success"]) - int(stale["success"]), dtype=np.int8
            ),
            "terminal_privileged_progress_difference": np.asarray(
                fresh["terminal"]["normalized_score"]
                - stale["terminal"]["normalized_score"],
                dtype=np.float32,
            ),
            "fresh_minus_stale_remaining_steps_after_h6": np.asarray(
                fresh["remaining_steps_after_h6"] - stale["remaining_steps_after_h6"],
                dtype=np.int32,
            ),
            "fresh_minus_stale_remaining_policy_calls": np.asarray(
                fresh["remaining_policy_calls"] - stale["remaining_policy_calls"],
                dtype=np.int16,
            ),
            "fresh_minus_stale_remaining_policy_wall_ms": np.asarray(
                fresh["remaining_policy_wall_ms"] - stale["remaining_policy_wall_ms"],
                dtype=np.float32,
            ),
            "fresh_minus_stale_remaining_elapsed_wall_ms": np.asarray(
                fresh["remaining_elapsed_wall_ms"] - stale["remaining_elapsed_wall_ms"],
                dtype=np.float32,
            ),
            "stale_decision_to_terminal_policy_calls": np.asarray(
                stale["remaining_policy_calls"], dtype=np.int16
            ),
            "fresh_decision_to_terminal_policy_calls": np.asarray(
                1 + fresh["remaining_policy_calls"], dtype=np.int16
            ),
            "stale_decision_to_terminal_policy_wall_ms": np.asarray(
                stale["remaining_policy_wall_ms"], dtype=np.float32
            ),
            "fresh_decision_to_terminal_policy_wall_ms": np.asarray(
                float(endpoint_fresh_result["collector_wall_ms"])
                + fresh["remaining_policy_wall_ms"],
                dtype=np.float32,
            ),
            "physical_collector_pair_policy_calls": np.asarray(
                2 + stale["remaining_policy_calls"] + fresh["remaining_policy_calls"],
                dtype=np.int16,
            ),
            "physical_collector_pair_policy_wall_ms": np.asarray(
                float(anchor_result["collector_wall_ms"])
                + float(endpoint_fresh_result["collector_wall_ms"])
                + stale["remaining_policy_wall_ms"]
                + fresh["remaining_policy_wall_ms"],
                dtype=np.float32,
            ),
        }
    )
    return arrays


