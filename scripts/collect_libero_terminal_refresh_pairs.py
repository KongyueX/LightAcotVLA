"""Collect terminal stale-vs-refresh outcomes after controlled Task8 H4 branches.

For every selected episode this collector follows the nominal cached-H10
trajectory to macro root 10, obtains one common Action-CoT anchor, and captures
one canonical pre-H4 simulator snapshot.  Five controlled H4 prefixes are
generated by ``collect_action_cot_state_branches.make_branch_actions``.  At
each valid branch endpoint, two terminal arms start from the exact same
post-H4 snapshot:

* stale: execute cached anchor actions 4:10;
* fresh: execute actions 0:6 from one common exact endpoint Action-CoT call.

After H6, both arms perform ordinary full-H10 replanning until success or the
original LIBERO episode limit.  Replanning seeds are assigned to preregistered
absolute decision slots ``anchor_step + 10 + 10*j`` shared by both arms, so arm
timing drift cannot change policy sampling.  Common sunk anchor cost, the fresh
decision RPC, and arm-specific decision-to-terminal costs are kept separate.

One compressed NPZ per ``(episode, root, branch)`` is the resume authority.
The main episode ends after root 10; branch rollouts never alter its trajectory.
Episodes 10-29 are explicitly forbidden because they are reserved for formal
evaluation.
"""
