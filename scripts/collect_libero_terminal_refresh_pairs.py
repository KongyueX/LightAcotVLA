def _scalar(arrays: Any, name: str) -> Any:
    return np.asarray(arrays[name]).reshape(()).item()


def _scalar_or_default(arrays: Any, name: str, default: Any) -> Any:
    if name not in arrays:
        return default
    return _scalar(arrays, name)


