def _validate_args(args: argparse.Namespace) -> None:
    if args.task_id < 0:
        raise ValueError("--task-id must be non-negative.")
    if args.root_index != FIXED_ROOT_INDEX:
        raise ValueError(f"This protocol is fixed to --root-index {FIXED_ROOT_INDEX}.")
    if not args.episode_ids or any(value < 0 for value in args.episode_ids):
        raise ValueError("--episode-ids must contain non-negative IDs.")
    if len(set(args.episode_ids)) != len(args.episode_ids):
        raise ValueError("--episode-ids must not contain duplicates.")
    forbidden = sorted(value for value in args.episode_ids if 10 <= value <= 29)
    if forbidden:
        raise ValueError(
            f"Episodes 10-29 are reserved for formal evaluation and forbidden here: {forbidden}."
        )
    paired_collector._validate_args(
        argparse.Namespace(
            task_id=args.task_id,
            episode_ids=args.episode_ids,
            root_indices=[args.root_index],
            branches=args.branches,
            seed=args.seed,
            num_steps_wait=args.num_steps_wait,
            resize_size=args.resize_size,
            action_cot_denoising_steps=args.action_cot_denoising_steps,
            continuation_seed_offset=1,
        )
    )


def _pair_path(
    root_dir: pathlib.Path,
    task_id: int,
    episode_id: int,
    root_index: int,
    branch: paired_collector.BranchSpec,
) -> pathlib.Path:
    return root_dir / (
        f"task{task_id:02d}_episode{episode_id:03d}_root{root_index:03d}_"
        f"branch{branch.branch_id:02d}_{branch.name}.npz"
    )


def _logical_slot_step(anchor_decision_step: int, slot: int) -> int:
    return anchor_decision_step + ANCHOR_HORIZON + BRANCH_HORIZON + slot * ACTION_HORIZON


def _logical_seed(
    *,
    episode_id: int,
    anchor_decision_step: int,
    slot: int,
    args: argparse.Namespace,
) -> int:
    return state_branches.canonical_policy_seed(
        args.seed,
        args.task_id,
        episode_id,
        _logical_slot_step(anchor_decision_step, slot),
    )


def _terminal_reason(
    *,
    success: bool,
    done: bool,
    absolute_step: int,
    step_limit: int,
    no_progress: bool,
) -> str:
    if success:
        return "success"
    if done:
        return "environment_done"
    if absolute_step >= step_limit:
        return "step_limit"
    if no_progress:
        return "no_environment_progress"
    return "stopped"


def _run_terminal_arm(
    env: Any,
    endpoint_snapshot: state_branches.CanonicalSimulatorSnapshot,
    h6_actions: np.ndarray,
    *,
    endpoint_absolute_step: int,
    step_limit: int,
    episode_id: int,
    anchor_decision_step: int,
    task_description: str,
    args: argparse.Namespace,
    client: websocket_policy.WebsocketClientPolicy,
) -> dict[str, Any]:
    arm_started = time.perf_counter()
    observation = state_branches._restore_canonical_snapshot(env, endpoint_snapshot)
    before = refresh_collector._progress(env, observation)
    h6_started = time.perf_counter()
    h6_budget = max(0, min(BRANCH_HORIZON, step_limit - endpoint_absolute_step))
    observation, done, executed_h6 = state_branches._step_actions(
        env,
        observation,
        np.asarray(h6_actions, dtype=np.float32)[:h6_budget, :ACTION_DIM],
    )
    absolute_step = endpoint_absolute_step + len(executed_h6)
    after_h6 = refresh_collector._progress(env, observation)
    h6_elapsed_wall_ms = (time.perf_counter() - h6_started) * 1000.0

    remaining_started = time.perf_counter()
    remaining_policy_calls = 0
    remaining_policy_wall_ms = 0.0
    remaining_steps = 0
    logical_seeds: list[int] = []
    no_progress = False
    while (
        not done
        and not after_h6["success"]
        and absolute_step < step_limit
    ):
        slot = remaining_policy_calls
        policy_seed = _logical_seed(
            episode_id=episode_id,
            anchor_decision_step=anchor_decision_step,
            slot=slot,
            args=args,
        )
        policy_input = paired_collector._policy_input(observation, task_description, args)
        result = paired_collector._teacher_request(
            client,
            policy_input,
            policy_seed=policy_seed,
            args=args,
        )
        tensors = paired_collector._teacher_tensors(result)
        remaining_policy_calls += 1
        remaining_policy_wall_ms += float(result["collector_wall_ms"])
        logical_seeds.append(policy_seed)
        action_budget = min(ACTION_HORIZON, step_limit - absolute_step)
        observation, done, executed = state_branches._step_actions(
            env,
            observation,
            tensors["actions_env"][:action_budget, :ACTION_DIM],
        )
        executed_count = len(executed)
        remaining_steps += executed_count
        absolute_step += executed_count
        if executed_count == 0:
            no_progress = True
            break
        if libero_eval._env_success(env):
            done = True
            break

    terminal = refresh_collector._progress(env, observation)
    h6_executed, h6_valid = refresh_collector._padded_executed(
        executed_h6,
        BRANCH_HORIZON,
    )
    success = bool(terminal["success"])
    return {
        "before": before,
        "after_h6": after_h6,
        "terminal": terminal,
        "terminal_reason": _terminal_reason(
            success=success,
            done=done,
            absolute_step=absolute_step,
            step_limit=step_limit,
            no_progress=no_progress,
        ),
        "h6_actions": np.asarray(h6_actions, dtype=np.float32)[:BRANCH_HORIZON, :ACTION_DIM],
        "h6_executed_actions": h6_executed,
        "h6_executed_valid": h6_valid,
        "h6_executed_steps": int(np.sum(h6_valid)),
        "remaining_steps_after_h6": remaining_steps,
        "endpoint_to_terminal_steps": len(executed_h6) + remaining_steps,
        "remaining_policy_calls": remaining_policy_calls,
        "remaining_policy_wall_ms": remaining_policy_wall_ms,
        "remaining_elapsed_wall_ms": (time.perf_counter() - remaining_started) * 1000.0,
        "h6_elapsed_wall_ms": h6_elapsed_wall_ms,
        "endpoint_to_terminal_elapsed_wall_ms": (time.perf_counter() - arm_started) * 1000.0,
        "logical_policy_seeds": np.asarray(logical_seeds, dtype=np.uint32),
        "terminal_absolute_step": absolute_step,
        "success": success,
    }


